func BenchmarkMatch(b *testing.B) {
	for _, name := range []string{
		"main.go", "LICENSE", "packages/parser/vendor/src/parser_test.go",
		"packages/api/src/__pycache__/app.pyc", "packages/ui/project.tsbuildinfo",
		"packages/api/.pytest_cache/v/cache/nodeids",
		"packages/ui/Form.DESIGNER.CS", "packages/ui/app.min.js",
	} {
		b.Run(name, func(b *testing.B) {
			b.ReportAllocs()
			for b.Loop() {
				_, _ = roles.Match(name)
			}
		})
	}
}

func BenchmarkClassify(b *testing.B) {
	b.ReportAllocs()
	for b.Loop() {
		_, _ = roles.Classify("packages/parser/vendor/src/parser_test.go")
	}
}

func BenchmarkMillionPaths(b *testing.B) {
	paths := make([]string, 1_000_000)
	for i := range paths {
		paths[i] = fmt.Sprintf("packages/p%d/src/file%d_test.go", i/1000, i)
	}
	b.ResetTimer()
	b.ReportAllocs()
	for b.Loop() {
		for _, name := range paths {
			_, _ = roles.Match(name)
		}
	}
	b.ReportMetric(float64(b.Elapsed().Nanoseconds())/float64(b.N*len(paths)), "ns/path")
}

func BenchmarkWalk(b *testing.B) {
	tree := fstest.MapFS{}
	for i := range 10_000 {
		tree[fmt.Sprintf("packages/p%d/src/file%d.go", i/100, i)] = &fstest.MapFile{}
	}
	b.ResetTimer()
	b.ReportAllocs()
	for b.Loop() {
		if err := roles.Walk(tree, roles.WalkOptions{}, func(string, roles.Result) error { return nil }); err != nil {
			b.Fatal(err)
		}
	}
}

